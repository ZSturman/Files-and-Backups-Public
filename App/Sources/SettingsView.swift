import FileCore
import SwiftUI

struct SettingsView: View {
    @Environment(AppModel.self) private var model
    @State private var stagingUsed: Int64 = 0

    var body: some View {
        @Bindable var model = model
        NavigationStack {
            Form {
                HomePageExportSettings()
                Section {
                    Toggle("Verify uploads by reading them back", isOn: $model.verifyByReadBack)
                } footer: {
                    Text("Reads each uploaded file back and compares SHA-256 before publishing it. Without this, only the size is checked. Read-back doubles traffic over slow links.")
                }
                Section {
                    Picker("Transfer storage limit", selection: $model.stagingQuotaGB) {
                        ForEach([2, 5, 10, 20, 50], id: \.self) { Text("\($0) GB").tag($0) }
                    }
                    LabeledContent("In use", value: Format.bytes(stagingUsed))
                } footer: {
                    Text("Imported files are copied here until their upload finishes, so queued uploads survive closing the app or going offline.")
                }
                Section("Connections") {
                    NavigationLink("Pi Connection · Scan or Paste") { FilesPiConnection() }
                    LabeledContent("Saved destinations", value: "\(model.connections.count)")
                    Text("Passwords and tokens are stored separately per destination in the Keychain on this device only.")
                        .font(.footnote).foregroundStyle(.secondary)
                }
                Section("About") {
                    NavigationLink("Open-Source Licenses") { LicensesView() }
                }
                Section("Limitations") {
                    Text("• SMB and SFTP uploads pause when iOS suspends the app and resume on reopen; WebDAV restarts the current file.\n• SMB, SFTP, and WebDAV have no restorable Trash; deletes are permanent.\n• Home Services uploads verify SHA-256 on the server; deletes go to its 7-day managed Trash.")
                        .font(.footnote)
                }
            }
            .formStyle(.grouped)
            .navigationTitle("Settings")
            .task { stagingUsed = model.stagingUsedBytes }
        }
    }
}

/// Bundled third-party notices, including the LGPL source offer for
/// AMSMB2/libsmb2 (generated by scripts/update-licenses.sh).
struct LicensesView: View {
    private let text: String = {
        guard let url = Bundle.main.url(forResource: "Acknowledgements", withExtension: "txt"),
              let text = try? String(contentsOf: url, encoding: .utf8) else { return "Licenses unavailable." }
        return text
    }()

    var body: some View {
        ScrollView {
            Text(text)
                .font(.system(.caption, design: .monospaced))
                .textSelection(.enabled)
                .frame(maxWidth: .infinity, alignment: .leading)
                .padding()
        }
        .navigationTitle("Licenses")
    }
}
